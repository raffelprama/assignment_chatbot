"""Build demo/transcript.md: the assignment's "demonstration of at least 5 questions".

By default it formats questions from a finished evaluation run (real system output, not edited);
`--live` asks them again against the running configuration.

    python -m demo.build_transcript                 # from eval/reports/runs/<run>.jsonl
    python -m demo.build_transcript --live
"""

import argparse
import asyncio
import json
from pathlib import Path

from app.chat import ask
from app.config import get_settings
from app.graph.build import attach_graph
from app.services import build_services
from eval.run import REPORTS, load_questions

OUT = Path(__file__).resolve().parent / "transcript.md"

DEMO = [
    ("Answerable", ["A1", "A9", "A10", "M2", "L1"]),
    ("Ambiguous / hard", ["H1", "H2", "H4", "M1", "X2"]),
    ("Not supported by the documents", ["U1", "U2", "U5", "U8", "X1"]),
]


def _format(question: str, result: dict) -> list[str]:
    lines = [f"**Q:** {question}", "", f"**Status:** `{result['status']}`  ", f"**A:** {result['answer']}"]
    if result.get("missing"):
        lines.append(f"  \n**Not specified in the SOPs:** {result['missing']}")
    if result.get("citations"):
        lines.append("")
        lines.append("Sources:")
        for c in result["citations"]:
            section = f"§{c['section_no']} {c['section_title']}" if c["section_no"] else "document overview"
            pages = ", ".join(str(p) for p in c["pages"])
            lines.append(f"- `{c['file_name']}`, page {pages}, {section} — “{c['quote']}”")
    usage, timings = result["usage"], result["timings_ms"]
    lines.append("")
    lines.append(f"<sub>{timings['total'] / 1000:.1f} s · {usage['llm_calls']} LLM calls · "
                 f"{usage['input_tokens']} in / {usage['output_tokens']} out tokens · judge: {result['judge']} · "
                 f"route: {' → '.join(result['route'])}</sub>")
    return lines


async def _live(ids: list[str]) -> dict[str, dict]:
    services = attach_graph(build_services(get_settings()))
    try:
        questions = {q["id"]: q["question"] for q in load_questions(set(ids))}
        return {qid: await ask(services, questions[qid]) for qid in ids}
    finally:
        await services.close()


def _from_run(run: str) -> dict[str, dict]:
    rows = [json.loads(l) for l in (REPORTS / "runs" / f"{run}.jsonl").read_text(encoding="utf-8").splitlines() if l]
    return {r["id"]: r["result"] for r in rows}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run", default="baseline")
    parser.add_argument("--live", action="store_true")
    args = parser.parse_args()
    ids = [qid for _, group in DEMO for qid in group]
    results = asyncio.run(_live(ids)) if args.live else _from_run(args.run)
    questions = {q["id"]: q["question"] for q in load_questions()}
    source = "live run" if args.live else f"evaluation run `{args.run}` (eval/reports/runs/{args.run}.jsonl)"
    lines = ["# Demo transcript", "",
             f"Generated by `python -m demo.build_transcript` from the {source}. Output is unedited.", ""]
    for title, group in DEMO:
        lines += [f"## {title}", ""]
        for qid in group:
            lines += [f"### {qid}", ""] + _format(questions[qid], results[qid]) + [""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
