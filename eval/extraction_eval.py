"""Extraction accuracy, measured rather than assumed.

1. Vision accuracy with free ground truth: KB_02/KB_03 have real text layers, so the vision path is
   forced on them and compared with the text layer (character error rate + exact-number check).
2. Scans: the KB_01/KB_04 vision transcriptions (from the committed artefacts) are compared with
   hand transcriptions in eval/gold/ (made by reading the page images; spot-check them).
3. Two columns: KB_03 read by a naive top-to-bottom/left-to-right reader vs the column-aware reader.

    python -m eval.extraction_eval        # writes eval/reports/extraction.md
"""

import asyncio
import re
from pathlib import Path

from pypdf import PdfReader

from app.config import get_settings
from app.ingestion.extract import PageText, collect_runs, extract_pages, naive_position_order
from app.ingestion.pipeline import load_artifact
from app.ingestion.structure import parse_document, validate
from app.llm.factory import LLM

ROOT = Path(__file__).resolve().parent
KB = get_settings().data_dir / "kb"


def normalize(text: str) -> str:
    text = re.sub(r"(?m)^\s*\d{1,3}\s*$", "", text)  # bare page numbers are not content
    return re.sub(r"\s+", " ", text).strip()


def char_error_rate(reference: str, hypothesis: str) -> float:
    ref, hyp = normalize(reference), normalize(hypothesis)
    previous = list(range(len(hyp) + 1))
    for i, ref_char in enumerate(ref, 1):
        current = [i]
        for j, hyp_char in enumerate(hyp, 1):
            current.append(min(previous[j] + 1, current[j - 1] + 1, previous[j - 1] + (ref_char != hyp_char)))
        previous = current
    return previous[-1] / max(1, len(ref))


def missing_numbers(reference: str, hypothesis: str) -> list[str]:
    return [n for n in re.findall(r"\d+(?:[.,:\-]\d+)*", normalize(reference)) if n not in normalize(hypothesis)]


async def vision_vs_text_layer(name: str, llm: LLM) -> dict:
    data = (KB / f"{name}.pdf").read_bytes()
    settings = get_settings()
    truth, _ = await extract_pages(data, llm, settings)
    vision, usages = await extract_pages(data, llm, settings, force_vision=True)
    doc = parse_document(vision, name)
    return {
        "doc": name,
        "cer": char_error_rate(truth[0].text, vision[0].text),
        "missing_numbers": missing_numbers(truth[0].text, vision[0].text),
        "sections": len(doc.sections),
        "validator": validate(doc),
        "layout_seen": vision[0].layout,
        "model": usages[0].model,
    }


def scan_vs_gold(name: str) -> dict:
    artifact = load_artifact(get_settings(), name)
    gold = (ROOT / "gold" / f"{name}.txt").read_text(encoding="utf-8")
    text = "\n".join(page["text"] for page in artifact["pages"])
    return {
        "doc": name,
        "method": artifact["pages"][0]["method"],
        "cer": char_error_rate(gold, text),
        "missing_numbers": missing_numbers(gold, text),
        "sections": len(artifact["sections"]),
        "validator": artifact["report"]["validator"],
    }


def column_demo() -> dict:
    page = PdfReader(KB / "KB_03_Panduan_Operasional_Layanan.pdf").pages[0]
    naive = PageText(1, "text_layer", "unknown", naive_position_order(collect_runs(page)), "naive")
    naive_doc = parse_document([naive], "KB_03")
    aware = load_artifact(get_settings(), "KB_03_Panduan_Operasional_Layanan")
    return {
        "naive_sections": [s.section_no for s in naive_doc.sections],
        "naive_validator": validate(naive_doc),
        "naive_first_line": naive_doc.sections[0].text[:120],
        "aware_sections": [s["section_no"] for s in aware["sections"]],
        "aware_layout": aware["pages"][0]["layout"],
    }


def render(vision_rows: list[dict], scan_rows: list[dict], columns: dict) -> str:
    lines = ["# Extraction evaluation", "", "Generated by `python -m eval.extraction_eval`.", ""]
    lines += ["## 1. Vision path vs ground-truth text layer (KB_02, KB_03)", "",
              "| Document | CER | Numbers missing | Sections | Validator | Layout seen | Model |",
              "|---|---|---|---|---|---|---|"]
    for r in vision_rows:
        lines.append(f"| {r['doc']} | {r['cer']:.4f} | {r['missing_numbers'] or 'none'} | {r['sections']} | "
                     f"{r['validator'] or 'ok'} | {r['layout_seen']} | {r['model']} |")
    lines += ["", "## 2. Scanned files: vision transcription vs hand transcription (KB_01, KB_04)", "",
              "| Document | Method | CER | Numbers missing | Sections | Validator |", "|---|---|---|---|---|---|"]
    for r in scan_rows:
        lines.append(f"| {r['doc']} | {r['method']} | {r['cer']:.4f} | {r['missing_numbers'] or 'none'} | "
                     f"{r['sections']} | {r['validator'] or 'ok'} |")
    lines += ["", "The gold transcriptions were typed from the page images and need a human spot-check.", "",
              "## 3. Two columns (KB_03)", "",
              f"- Naive top-to-bottom reader: sections found {columns['naive_sections']}; validator: "
              f"{columns['naive_validator']}",
              f"- Naive reader, start of §1: `{columns['naive_first_line']}`",
              f"- Column-aware reader: layout `{columns['aware_layout']}`, sections {columns['aware_sections']}", ""]
    return "\n".join(lines)


async def main() -> None:
    llm = LLM(get_settings())
    vision_rows = [await vision_vs_text_layer(n, llm) for n in
                   ("KB_02_Pengelolaan_Keluhan_Pelanggan", "KB_03_Panduan_Operasional_Layanan")]
    scan_rows = [scan_vs_gold(n) for n in ("KB_01_Penanganan_Tiket_Layanan", "KB_04_Eskalasi_dan_Insiden")]
    report = render(vision_rows, scan_rows, column_demo())
    out = ROOT / "reports" / "extraction.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    asyncio.run(main())
